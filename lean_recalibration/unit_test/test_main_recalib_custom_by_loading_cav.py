# build_class_concepts_map
# ---------------------------------------------------------------------------
@pytest.mark.unit
class TestBuildClassConceptsMap:
    def test_groups_concepts_by_matching_class_name(self):
        manifest_data = {
            "concepts": {
                "cat_spots": {"class_name": "cat"},
                "cat_ears": {"class_name": "cat"},
                "dog_collar": {"class_name": "dog"},
            }
        }
        class_names = ["bird", "cat", "dog"]  # alphabetically sorted, as get_class_folder_dicts does
        target_idx_list = [1, 2, 0]  # cat=1, dog=2, bird=0 (positional against TARGET_CLASS_LIST)
        result = recalib.build_class_concepts_map(manifest_data, class_names, target_idx_list)
        assert sorted(result[1]) == ["cat_ears", "cat_spots"]
        assert result[2] == ["dog_collar"]
        assert result[0] == []  # bird has no concepts in the manifest

    def test_empty_manifest_yields_empty_lists_for_every_target(self):
        result = recalib.build_class_concepts_map({}, ["cat", "dog"], [0, 1])
        assert result == {0: [], 1: []}

    def test_concept_with_unmatched_class_name_is_ignored(self):
        manifest_data = {"concepts": {"orphan": {"class_name": "not_a_real_class"}}}
        result = recalib.build_class_concepts_map(manifest_data, ["cat", "dog"], [0, 1])
        assert result == {0: [], 1: []}


