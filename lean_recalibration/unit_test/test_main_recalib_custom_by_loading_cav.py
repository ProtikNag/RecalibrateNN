# _resolve_layer_combos
# ---------------------------------------------------------------------------
@pytest.mark.unit
class TestResolveLayerCombos:
    def test_no_groups_three_layers_gives_seven_combos(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        combos = recalib._resolve_layer_combos(
            list(C.PROCESSED_LAYER_NAMES), use_groups=False, registry=registry, model_name="vgg16",
        )
        # C(3,1) + C(3,2) + C(3,3) = 3 + 3 + 1 = 7
        assert len(combos) == 7
        assert [C.PROCESSED_LAYER_NAMES[0]] in combos
        assert list(C.PROCESSED_LAYER_NAMES) in combos

    def test_no_groups_single_layer_gives_one_combo(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        combos = recalib._resolve_layer_combos(
            ["features.6"], use_groups=False, registry=registry, model_name="vgg16",
        )
        assert combos == [["features.6"]]

    def test_use_groups_with_no_manifest_groups_falls_back_to_combinations(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        combos = recalib._resolve_layer_combos(
            ["features.6"], use_groups=True, registry=registry, model_name="vgg16",
        )
        assert combos == [["features.6"]]

    def test_use_groups_with_matching_manifest_group_uses_its_layers(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        registry.save_layer_cav(
            model="vgg16", layer="features.3",
            concept_cavs={"concept_a": torch.zeros(8)},
            concept_aliases={"concept_a": "concept_a"},
        )
        registry.add_layer_group("mygroup", model="vgg16", layers=["features.3"])
        # layer_names is irrelevant once a matching group exists -- the group's own
        # layers list is used instead.
        combos = recalib._resolve_layer_combos(
            ["features.3", "features.5", "features.6"], use_groups=True, registry=registry, model_name="vgg16",
        )
        assert combos == [["features.3"]]


