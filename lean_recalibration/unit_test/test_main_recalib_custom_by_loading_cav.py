@pytest.mark.unit
class TestLoadTargetCavs:
    def test_found_cav_is_l2_normalized_and_reshaped_to_1xN(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        raw = torch.tensor([3.0, 4.0])  # norm = 5
        registry.save_layer_cav(
            model="vgg16", layer="features.3",
            concept_cavs={"concept_a": raw},
            concept_aliases={"concept_a": "concept_a"},
        )
        logger = _CollectingLogger()
        result = recalib._load_target_cavs(registry, "vgg16", ["features.3"], "concept_a", logger)
        assert set(result.keys()) == {"features.3"}
        cav = result["features.3"]
        assert cav.shape == (1, 2)
        assert torch.allclose(cav.norm(), torch.tensor(1.0), atol=1e-5)
        assert any(level == "info" for level, _ in logger.lines)

    def test_missing_concept_is_skipped_with_warning(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        logger = _CollectingLogger()
        result = recalib._load_target_cavs(registry, "vgg16", ["features.3"], "no_such_concept", logger)
        assert result == {}
        assert any(level == "warning" for level, _ in logger.lines)


@pytest.mark.unit
class TestLoadClassConceptCavs:
    def test_concepts_with_cavs_are_included_keyed_by_concept_name(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        registry.save_layer_cav(
            model="vgg16", layer="features.3",
            concept_cavs={"concept_a": torch.tensor([1.0, 0.0])},
            concept_aliases={"concept_a": "concept_a"},
        )
        logger = _CollectingLogger()
        result = recalib._load_class_concept_cavs(registry, "vgg16", ["features.3"], ["concept_a"], logger)
        assert set(result.keys()) == {"concept_a"}
        assert set(result["concept_a"].keys()) == {"features.3"}

    def test_concept_with_no_cavs_anywhere_is_omitted_with_warning(self, tmp_path):
        registry = CAVRegistry.create_empty_manifest(str(tmp_path / "cav_store"))
        logger = _CollectingLogger()
        result = recalib._load_class_concept_cavs(registry, "vgg16", ["features.3"], ["ghost_concept"], logger)
        assert result == {}
        assert any(level == "warning" for level, _ in logger.lines)


