@pytest.mark.unit
class TestExtractImagesAndLabels:
    def test_tuple_batch_splits_images_and_labels(self):
        imgs = torch.zeros(2, 3, 4, 4)
        labels = torch.tensor([0, 1])
        out_imgs, out_labels = recalib._extract_images_and_labels((imgs, labels))
        assert out_imgs is imgs
        assert out_labels is labels

    def test_bare_tensor_batch_has_no_labels(self):
        imgs = torch.zeros(2, 3, 4, 4)
        out_imgs, out_labels = recalib._extract_images_and_labels(imgs)
        assert out_imgs is imgs
        assert out_labels is None

    def test_single_element_list_batch_has_no_labels(self):
        imgs = torch.zeros(2, 3, 4, 4)
        out_imgs, out_labels = recalib._extract_images_and_labels([imgs])
        assert out_imgs is imgs
        assert out_labels is None


