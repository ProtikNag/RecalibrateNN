@pytest.mark.integration
@pytest.mark.slow
class TestMainRecalibCli:
    def test_missing_config_file_arg_errors_cleanly(self, run_script):
        result = run_script(
            "main_recalib_custom_by_loading_cav.py",
            ["--model_name", "vgg16", "--model_path", C.SINGLE_MODEL_ROOT],
        )
        assert result.returncode != 0
        assert "config_file" in result.stderr.lower()

    def test_nonexistent_config_file_path_errors_cleanly(self, run_script, tmp_path):
        bogus = str(tmp_path / "does_not_exist.yaml")
        result = run_script(
            "main_recalib_custom_by_loading_cav.py",
            [
                "--model_name", "vgg16",
                "--model_path", C.SINGLE_MODEL_ROOT,
                "--config_file", bogus,
                "--cav_store", C.SINGLE_CAV_STORE,
            ],
        )
        assert result.returncode != 0
        assert "Config file not found" in result.stderr

    def test_single_class_end_to_end(self, run_script, tmp_path, populated_single_cav_store):
        results_dir = str(tmp_path / "results")
        result = run_script(
            "main_recalib_custom_by_loading_cav.py",
            [
                "--model_name", C.MODEL_NAME,
                "--model_path", C.SINGLE_MODEL_ROOT,
                "--config_file", C.SINGLE_CONFIG_RECALIB_PATH,
                "--cav_store", populated_single_cav_store,
                "--store_results", results_dir,
            ],
            timeout=600,
        )
        result.assert_success()

        model_dir = os.path.join(results_dir, C.MODEL_NAME)
        assert os.path.isfile(os.path.join(model_dir, "accuracy_results_before.txt"))
        assert os.path.isfile(os.path.join(model_dir, f"layer_combinations_{C.MODEL_NAME}.txt"))
        assert os.path.isfile(os.path.join(model_dir, f"recalibration_combo_accuracy_{C.MODEL_NAME}.csv"))
        assert os.path.isfile(os.path.join(model_dir, f"recalibration_summary_{C.MODEL_NAME}.xlsx"))
        # At least one recalibrated model checkpoint (for the "cat" class, which owns the
        # only concept mapped to it via config.CONCEPT_FOLDER_LIST fallback).
        pth_files = [f for f in os.listdir(model_dir) if f.startswith("model_cls") and f.endswith(".pth")]
        assert pth_files, f"No recalibrated model checkpoints found in {model_dir}"

    def test_multiclass_joint_end_to_end(self, run_script, tmp_path, populated_multi_cav_store):
        results_dir = str(tmp_path / "results")
        result = run_script(
            "main_recalib_custom_by_loading_cav.py",
            [
                "--model_name", C.MODEL_NAME,
                "--model_path", C.MULTI_MODEL_ROOT,
                "--config_file", C.MULTI_CONFIG_RECALIB_PATH,
                "--cav_store", populated_multi_cav_store,
                "--store_results", results_dir,
                "--multiclass_recalibration_mode",
            ],
            timeout=600,
        )
        result.assert_success()
        assert "multiclass_recalibration_mode=True" in result.stdout

        model_dir = os.path.join(results_dir, C.MODEL_NAME)
        assert os.path.isfile(os.path.join(model_dir, "accuracy_results_before.txt"))
        assert os.path.isfile(
            os.path.join(model_dir, f"recalibration_multiclass_combo_accuracy_{C.MODEL_NAME}.csv")
        )
        assert os.path.isfile(os.path.join(model_dir, f"recalibration_summary_{C.MODEL_NAME}.xlsx"))
        pth_files = [f for f in os.listdir(model_dir) if f.startswith("model_multiclass_combo") and f.endswith(".pth")]
        assert pth_files, f"No joint recalibrated model checkpoints found in {model_dir}"
