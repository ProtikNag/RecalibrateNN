"""
Unit + CLI/integration tests for lean_recalibration/main_recalib_custom_by_loading_cav.py.

Unlike main_store_cav.py, this script DOES expose reusable ``main()``/``main_multiclass()``
functions, but they still require a fully-populated CAVRegistry, DataLoaders, etc. to run --
so the full pipeline is still exercised via subprocess (the ``run_script`` fixture), reusing
CAV stores pre-populated ONCE per session by ``main_store_cav.py`` (see
``populated_single_cav_store`` / ``populated_multi_cav_store`` in conftest.py). Pure helper
functions (``_extract_images_and_labels``, ``load_model_manifest``, ``build_class_concepts_map``,
``_resolve_layer_combos``, ``_load_target_cavs``, ``_load_class_concept_cavs``) are unit-tested
in-process for speed and precision.

The CLI/integration tests use the *_recalib fast config variants (single VGG layer,
override_retraining=True) generated by generate_test_data.py, which collapse
``_resolve_layer_combos()`` to exactly one combination so the real gradient-descent training
loop stays fast; the full 7-combination math is covered directly by
``TestResolveLayerCombos.test_no_groups_three_layers_gives_seven_combos`` instead.
"""

import json
import os

import pytest
import torch

import main_recalib_custom_by_loading_cav as recalib
from cav_registry import CAVRegistry

from helpers import constants as C


class _CollectingLogger:
    def __init__(self):
        self.lines = []

    def info(self, msg):
        self.lines.append(("info", msg))

    def warning(self, msg):
        self.lines.append(("warning", msg))

    def error(self, msg):
        self.lines.append(("error", msg))


